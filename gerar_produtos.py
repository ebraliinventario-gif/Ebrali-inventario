def processar_produtos():
    """Processa a lista CSV e gera o objeto JavaScript."""
    produtos_dict = {}
    
    for linha in PRODUTOS_CSV.strip().split('\n'):
        linha = linha.strip()
        if not linha or not ';' in linha:
            continue
        
        partes = linha.split(';')
        if len(partes) < 3:
            continue
        
        codigo = partes[0].strip()
        produto = partes[1].strip()
        embalagem = partes[2].strip()
        observacao = partes[3].strip() if len(partes) > 3 else ''
        
        # Criar objeto do produto
        produto_obj = {
            'produto': produto,
            'embalagem': embalagem
        }
        
        if observacao:
            produto_obj['observacao'] = observacao
        
        produtos_dict[codigo] = produto_obj
    
    return produtos_dict


def gerar_javascript(produtos_dict):
    """Gera o código JavaScript do objeto PRODUTOS."""
    linhas = ['        const PRODUTOS = {']
    
    codigos_ordenados = sorted(produtos_dict.keys(), key=lambda x: (
        len(x), x.replace('A', '').replace('N', '').replace(',', '').replace('.', '').isdigit() and int(x.replace('A', '').replace('N', '').replace(',', '').replace('.', '') or '0') or 999999,
        x
    ))
    
    for i, codigo in enumerate(codigos_ordenados):
        produto = produtos_dict[codigo]
        produto_str = produto['produto'].replace("'", "\\'")
        embalagem_str = produto['embalagem'].replace("'", "\\'")
        
        linha = f"            '{codigo}': {{ produto: '{produto_str}', embalagem: '{embalagem_str}'"
        
        if 'observacao' in produto:
            linha += f", observacao: '{produto['observacao']}'"
        
        linha += ' }'
        
        if i < len(codigos_ordenados) - 1:
            linha += ','
        
        linhas.append(linha)
    
    linhas.append('        };')
    
    return '\n'.join(linhas)


